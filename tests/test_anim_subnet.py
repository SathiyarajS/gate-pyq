def test_audited_membership():
    assert set(SPECS) == set(AUDIT)
    assert not set(EXCLUDED) & set(SPECS)
    assert family.PLAYER == 'subnet'
    assert family.TABS


@pytest.mark.parametrize('qid', AUDIT)
def test_complete_inputs_and_keyed_content(qid):
    q, audit = QUESTIONS[qid], AUDIT[qid]
    assert hashlib.sha256(q['question_text'].encode()).hexdigest() == audit['question_sha256']
    assert (q.get('official_answer') or q['derived_answer']) == audit['key']
    assert SPECS[qid] == audit['spec']
    content = audit['option_content']
    if content is not None:
        for part in content if isinstance(content, list) else [content]:
            assert part in q['question_text']
    # The sole linked discrepancy is an expansion-of-CIDR typo, not arithmetic.
    assert not q.get('discrepancy_ids') or qid == 'CS-2026-S1-Q56'


@pytest.mark.parametrize('qid', AUDIT)
def test_trace_and_each_expectation_fail_closed(qid):
    spec = SPECS[qid]
    result = family.KINDS[spec['kind']](qid, spec)
    assert result['kind'] == spec['kind']
    assert result['count'] == sum(len(s['steps']) for s in result['schedules'])
    for schedule in result['schedules']:
        assert schedule['steps'][-1]['final'] is True
        assert all(s['note'].strip() and s['blocks'] is not None for s in schedule['steps'])
        assert not any(s.get('final') for s in schedule['steps'][:-1])
    for key in spec['expect']:
        bad = copy.deepcopy(spec)
        bad['expect'][key] = '__deliberately_incorrect__'
        with pytest.raises(SystemExit, match='Animation for'):
            family.KINDS[spec['kind']](qid, bad)


def test_fragmentation_byte_ranges_and_no_intermediate_reassembly():
    payload, frags, history = family.fragment_run({'total': 1420, 'mtus': [542, 360]}, 20)
    assert payload == 1400
    assert history[0][1] == [(0, 520, True), (520, 520, True), (1040, 360, False)]
    assert frags == [(0, 336, True), (336, 184, True), (520, 336, True),
                     (856, 184, True), (1040, 336, True), (1376, 24, False)]
    assert sum(n for _, n, _ in frags) == payload


def test_fragmentation_uses_eight_byte_offsets():
    _, frags, _ = family.fragment_run({'total': 4500, 'mtus': [600]}, 20)
    assert frags[:3] == [(0, 576, True), (576, 576, True), (1152, 576, True)]
    assert frags[-1] == (4032, 448, False)


def test_address_helpers_and_rejected_noncontiguous_mask():
    assert family.ip_text(family.ip('203.197.75.201') & family.mask_of(18)) == '203.197.64.0'
    assert family.prefix_of('255.255.248.0') == 21
    with pytest.raises(SystemExit):
        family.prefix_of('255.255.64.0')
    with pytest.raises(SystemExit):
        family.fragment([(0, 100, False)], 20, 20)


