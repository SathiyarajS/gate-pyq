def test_audited_membership():
    assert set(SPECS) == set(AUDIT)
    assert not set(EXCLUDED) & set(SPECS)
    assert family.PLAYER == 'window'
    assert family.TABS


@pytest.mark.parametrize('qid', AUDIT)
def test_complete_inputs_and_keyed_content(qid):
    q, audit = QUESTIONS[qid], AUDIT[qid]
    assert hashlib.sha256(q['question_text'].encode()).hexdigest() == audit['question_sha256']
    assert (q.get('official_answer') or q['derived_answer']) == audit['key']
    assert SPECS[qid] == audit['spec']
    content = audit['option_content']
    if content is not None:
        for part in content if isinstance(content, list) else [content]:
            assert part in q['question_text']
    # The sole linked discrepancy is an expansion-of-CIDR typo, not arithmetic.
    assert not q.get('discrepancy_ids') or qid == 'CS-2026-S1-Q56'


@pytest.mark.parametrize('qid', AUDIT)
def test_trace_and_each_expectation_fail_closed(qid):
    spec = SPECS[qid]
    result = family.KINDS[spec['kind']](qid, spec)
    assert result['kind'] == spec['kind']
    assert result['count'] == sum(len(s['steps']) for s in result['schedules'])
    for schedule in result['schedules']:
        assert schedule['steps'][-1]['final'] is True
        assert all(s['note'].strip() and s['blocks'] is not None for s in schedule['steps'])
        assert not any(s.get('final') for s in schedule['steps'][:-1])
    for key in spec['expect']:
        bad = copy.deepcopy(spec)
        bad['expect'][key] = '__deliberately_incorrect__'
        with pytest.raises(SystemExit, match='Animation for'):
            family.KINDS[spec['kind']](qid, bad)


def test_ack_serialization_and_asymmetric_rates():
    from fractions import Fraction
    m = family.arq_model(SPECS['CS-2016-S1-Q65'], 1000)
    assert m['t_tx'] == m['t_ack'] == Fraction(1, 10)
    assert m['cycle'] == Fraction(2, 5)
    assert family.arq_answer(SPECS['CS-2016-S1-Q65'], m) == {'throughput': 2500}


def test_window_rounds_up_and_retains_official_range():
    from fractions import Fraction
    spec = SPECS['CS-2021-S1-Q59']
    m = family.arq_model(spec, 1000)
    assert m['need'] == Fraction(20201, 400)
    assert m['W'] == 51
    assert 50 * m['t_tx'] < m['cycle'] / 2 <= 51 * m['t_tx']
    assert spec['expect']['window'] == [50, 52]


def test_go_back_n_loss_attempts_and_retransmissions():
    result = family.gbn_animation('losses', SPECS['CS-2006-Q46'])
    items = result['schedules'][0]['steps'][-1]['blocks'][0]['items']
    assert [x['p'] for x in items if x['n']] == [1,2,3,4,5,6,7,5,6,7,8,9,7,8,9,9]
    assert [x['n'] for x in items if x['s'] == 'lost'] == [5,10,15]


def test_sequence_bits_smallest_window_and_kilobyte_conventions():
    for kilo in (1000, 1024):
        m = family.arq_model(SPECS['CS-2016-S2-Q65'], kilo)
        assert (m['W'], m['k']) == (6, 4)
    spec = {'kind':'arq', 'frame_bits':100, 'rate':100, 'prop_ms':0,
            'goal':'seqbits', 'protocol':'gbn', 'target':1, 'expect':{'bits':1}}
    family.arq_animation('one-bit', spec)


def test_timeout_rounds_and_threshold_boundary():
    result = family.cwnd_animation('third', SPECS['CS-2024-S2-Q54'])
    assert result['schedules'][0]['steps'][-1]['blocks'][0]['rounds'] == [1,2,4]
    bad = copy.deepcopy(SPECS['CS-2024-S2-Q54'])
    bad['round'] = 4
    with pytest.raises(SystemExit, match='past the threshold'):
        family.cwnd_animation('ambiguous-boundary', bad)
