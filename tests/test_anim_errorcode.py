def test_audited_membership():
    assert set(SPECS) == set(AUDIT)
    assert not set(EXCLUDED) & set(SPECS)
    assert family.PLAYER == 'errorcode'
    assert family.TABS


@pytest.mark.parametrize('qid', AUDIT)
def test_complete_inputs_and_keyed_content(qid):
    q, audit = QUESTIONS[qid], AUDIT[qid]
    assert hashlib.sha256(q['question_text'].encode()).hexdigest() == audit['question_sha256']
    assert (q.get('official_answer') or q['derived_answer']) == audit['key']
    assert SPECS[qid] == audit['spec']
    content = audit['option_content']
    if content is not None:
        for part in content if isinstance(content, list) else [content]:
            assert part in q['question_text']
    # The sole linked discrepancy is an expansion-of-CIDR typo, not arithmetic.
    assert not q.get('discrepancy_ids') or qid == 'CS-2026-S1-Q56'


@pytest.mark.parametrize('qid', AUDIT)
def test_trace_and_each_expectation_fail_closed(qid):
    spec = SPECS[qid]
    result = family.KINDS[spec['kind']](qid, spec)
    assert result['kind'] == spec['kind']
    assert result['count'] == sum(len(s['steps']) for s in result['schedules'])
    for schedule in result['schedules']:
        assert schedule['steps'][-1]['final'] is True
        assert all(s['note'].strip() and s['blocks'] is not None for s in schedule['steps'])
        assert not any(s.get('final') for s in schedule['steps'][:-1])
    for key in spec['expect']:
        bad = copy.deepcopy(spec)
        bad['expect'][key] = '__deliberately_incorrect__'
        with pytest.raises(SystemExit, match='Animation for'):
            family.KINDS[spec['kind']](qid, bad)


@pytest.mark.parametrize('message,generator,remainder', [
    ('11001001','1001','011'), ('01011011','1011','101'),
    ('11000','1011','100'), ('110001011','1001','100')])
def test_crc_remainders_and_codeword_divisibility(message, generator, remainder):
    got, operations = family.mod2_divide(message + '000', generator)
    assert got == remainder
    assert family.mod2_divide(message + remainder, generator)[0] == '000'
    # Independently verify each XOR cancels the current leading bit.
    for column, before, after in operations:
        assert int(before, 2) ^ (int(generator, 2) << (len(before)-len(generator)-column)) == int(after, 2)
        assert after[column] == '0'


def test_distance_all_pairs():
    s = SPECS['CS-2017-S2-Q44']
    result = family.distance_animation('pairs', s)
    rows = result['schedules'][0]['steps'][-1]['blocks'][0]['rows']
    assert [int(r[2]) for r in rows] == [3,3,4,4,3,3]


def test_hamming_parity_is_inferred_not_assumed():
    s = copy.deepcopy(SPECS['CS-2021-S1-Q39'])
    # Changing a known parity bit makes the two fully known groups disagree.
    s['values']['c2'] = 0
    with pytest.raises(SystemExit, match='disagree'):
        family.hamming_animation('bad-parity', s)


def test_rejects_invalid_generators_and_words():
    for generator in ('0011', 'x^3+x^3+1', 'x^-1+1', '1'):
        with pytest.raises(SystemExit):
            family.poly_bits(generator)
    with pytest.raises(SystemExit):
        family.distance_animation('bad-code', {'codewords':['000','01x'], 'expect':{'correct':0}})
