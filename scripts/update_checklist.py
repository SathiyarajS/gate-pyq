#!/usr/bin/env python3
"""Regenerate the progress table in docs/CHECKLIST.md from the repository data.

Counts per paper (newest first, the HANDOFF.md order):
  drafted  - entries in data/transcriptions/<paper>.json
  verified - entries with status "verified"
  live     - entries the production loader accepts (the site shows them redrawn)
  figures  - figures/<paper>-Q*.svg files

Only the block between the AUTO markers is rewritten; the task list above it is
edited by hand. Run after every transcribe or review commit (HANDOFF.md 3.2/3.3).
"""
import json, re
from collections import Counter
from pathlib import Path
from transcription import load_paper, resolve

ROOT = Path(__file__).resolve().parents[1]
PATH = ROOT / 'docs/CHECKLIST.md'
START, END = '<!-- AUTO:progress:start -->', '<!-- AUTO:progress:end -->'


def order(paper):
    m = re.fullmatch(r'CS-(\d{4})(?:-S(\d))?', paper)
    return (int(m[1]), int(m[2] or 0))


def status(n, drafted, verified):
    if verified == n: return '✅ verified'
    if verified: return '🟡 review in progress'
    if drafted == n: return '🔵 drafted, awaiting review'
    if drafted: return '🟠 partly drafted'
    return '⬜ not started'


def main():
    questions = json.loads((ROOT / 'data/questions.json').read_text())
    totals = Counter(q['paper_id'] for q in questions)
    rows, sums = [], Counter()
    next_transcribe = next_review = None
    for paper in sorted(totals, key=order, reverse=True):
        data = load_paper(ROOT, paper)
        entries = {k: v for k, v in data.items() if k != '_contexts'}
        n, drafted = totals[paper], len(entries)
        verified = sum(1 for e in entries.values() if e.get('status') == 'verified')
        live = sum(bool(resolve(ROOT, q, data)) for q in questions if q['paper_id'] == paper)
        figures = len(list((ROOT / 'figures').glob(paper + '-Q*.svg')))
        rows.append(f'| {paper} | {n} | {drafted} | {verified} | {live} | {figures} | {status(n, drafted, verified)} |')
        sums.update(questions=n, drafted=drafted, verified=verified, live=live, figures=figures)
        if drafted < n and next_transcribe is None: next_transcribe = paper
        if drafted and verified < drafted and next_review is None: next_review = paper
    q = sums['questions']
    pct = lambda x: f'{100 * x / q:.1f}%'
    block = [START, '',
             f"**Overall:** {sums['drafted']}/{q} drafted ({pct(sums['drafted'])}) · "
             f"{sums['verified']}/{q} verified ({pct(sums['verified'])}) · {sums['live']} live on the site as redrawn text.",
             '',
             f'**Next to transcribe (prompt B):** {next_transcribe or "none"} · '
             f'**Next to review (prompt C):** {next_review or "none"}',
             '',
             '| Paper | Questions | Drafted | Verified | Live | Figures | Status |',
             '|---|---:|---:|---:|---:|---:|---|',
             *rows,
             f"| **Total** | **{q}** | **{sums['drafted']}** | **{sums['verified']}** | **{sums['live']}** | **{sums['figures']}** | |",
             '', 'Generated by `python scripts/update_checklist.py`; do not edit this table by hand.', '', END]
    text = PATH.read_text()
    if START not in text or END not in text: raise SystemExit('CHECKLIST.md is missing the AUTO markers')
    head, rest = text.split(START, 1)
    PATH.write_text(head + '\n'.join(block) + rest.split(END, 1)[1])


if __name__ == '__main__':
    main()
